#!/usr/bin/env python3
"""Write remake/art/BLOCKS.md: every combat block id and what it is.

    python3 tools/list_blocks.py [SOURCE]

(The reference pictures for each id come from tools/extract.py, which
writes extracted/blocks/<ID>.png and an index.md that shows them.)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))

from cok import blocks  # noqa: E402
from cok.gamefiles import GameFiles  # noqa: E402


def main():
    gf = GameFiles(sys.argv[1] if len(sys.argv) > 1 else None)
    out = os.path.join(HERE, '..', 'remake', 'art', 'BLOCKS.md')
    rows = blocks.catalogue(gf)
    with open(out, 'w') as f:
        f.write('# Combat block ids\n\n')
        f.write('Generated by `tools/list_blocks.py`. Pictures of the originals: run\n')
        f.write('`tools/extract.py` and open `extracted/blocks/index.md`.\n\n')
        f.write('| id | what |\n|----|------|\n')
        for bid, desc in rows:
            f.write('| `%s` | %s |\n' % (bid, desc))
    print('%d ids -> %s' % (len(rows), os.path.relpath(out)))


if __name__ == '__main__':
    main()
